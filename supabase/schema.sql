  ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'amayakids'
      AND column_name = 'id'
      AND is_identity = 'NO'
      AND column_default IS NULL
  ) THEN
